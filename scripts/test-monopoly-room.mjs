  assert.equal(room.pendingLanding, undefined, "完成落地操作后不应遗留待处理状态");
  assert.equal(room.game.properties[12].ownerDeviceId, "a", "购买应完成当前地块的唯一操作");
  assert.equal(room.game.currentPlayerId, "a", "12 点奖励应仍由当前玩家继续操作");
  assert.equal(room.turnRolled, false, "买地后应直接回到 12 点奖励的投骰前状态，不能继续升级同一地块");
