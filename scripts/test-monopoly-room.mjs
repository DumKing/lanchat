import assert from "node:assert/strict";
import { mkdir, mkdtemp, rm } from "node:fs/promises";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { build } from "esbuild";
import { reactive } from "vue";

const root = process.cwd();
const tempRoot = path.join(root, ".tmp");
await mkdir(tempRoot, { recursive: true });
const tempDir = await mkdtemp(path.join(tempRoot, "monopoly-room-"));
const outfile = path.join(tempDir, "monopoly-room.mjs");

try {
  await build({ entryPoints: [path.join(root, "src/games/monopolyRoom.ts")], outfile, bundle: true, format: "esm", platform: "node", logLevel: "silent" });
  const { applyMonopolyRoomAction, createMonopolyRoomState, planMonopolyBotAction } = await import(`${pathToFileURL(outfile).href}?t=${Date.now()}`);
  const host = { deviceId: "a", nickname: "甲", online: true, ready: false };
  let botRoom = createMonopolyRoomState({ roomId: "monopoly-bot", host, startingCoins: 5000, maxRounds: 20, now: 1 });
  botRoom = applyMonopolyRoomAction(botRoom, { action: "add_bot", hostId: "a", bot: { deviceId: "bot:monopoly-bot:1", nickname: "机器人 1", online: true, ready: false, isBot: true } });
  assert.equal(botRoom.seats.length, 2, "房主应能在大厅添加机器人座位");
  assert.equal(botRoom.seats[1]?.ready, true, "机器人加入后应自动准备");
  assert.equal(botRoom.game.players[1]?.isBot, true, "机器人应作为正常游戏玩家进入权威状态");
  botRoom = applyMonopolyRoomAction(botRoom, { action: "ready", playerId: "a", ready: true });
  botRoom = applyMonopolyRoomAction(botRoom, { action: "start", playerId: "a" });
  botRoom.game.currentPlayerId = "bot:monopoly-bot:1";
  const botRoll = planMonopolyBotAction(botRoom, "bot:monopoly-bot:1", () => .9);
  assert.deepEqual(botRoll, { action: "roll", playerId: "bot:monopoly-bot:1" }, "机器人在投骰阶段应自动投骰");
  botRoom.pendingLanding = { playerId: "bot:monopoly-bot:1", kind: "buy", index: 1 };
  const botBuy = planMonopolyBotAction(botRoom, "bot:monopoly-bot:1", () => .9);
  assert.deepEqual(botBuy, { action: "buy", playerId: "bot:monopoly-bot:1", propertyIndex: 1 }, "机器人金币充足时应购买空地");
  let room = createMonopolyRoomState({ roomId: "monopoly-1", host, startingCoins: 5000, maxRounds: 20, now: 1 });
  room = applyMonopolyRoomAction(room, { action: "join", player: { deviceId: "b", nickname: "乙", online: true, ready: false } });
  room = applyMonopolyRoomAction(reactive(room), { action: "ready", playerId: "a", ready: true });
  assert.equal(room.seats.find((seat) => seat.deviceId === "a")?.ready, true, "响应式房间状态应能正常执行准备操作");
  room = applyMonopolyRoomAction(room, { action: "ready", playerId: "b", ready: true });
  room = applyMonopolyRoomAction(room, { action: "start", playerId: "a" });
  assert.equal(room.phase, "playing");
  assert.equal(room.game.players.length, 2);
  room = applyMonopolyRoomAction(room, { action: "join", player: { deviceId: "c", nickname: "丙", online: true, ready: false } });
  assert.equal(room.seats.length, 2, "开局后的加入者不应占用骰序座位");
  assert.deepEqual(room.spectators.map((player) => player.deviceId), ["c"], "开局后的加入者应作为观众记录");
  room = applyMonopolyRoomAction(room, { action: "roll", playerId: "a" }, () => 0.999);
  assert.equal(room.game.players[0].position, 12, "双骰 6 + 6 应前进 12 格");
  assert.deepEqual({ ...room.lastDice, rolledAt: undefined }, { playerId: "a", nickname: "甲", values: [6, 6], total: 12, fixed: false, rolledAt: undefined }, "房间状态应同步本次骰子结果");
  assert.equal(typeof room.lastDice?.rolledAt, "number", "每次投骰都应携带独立的动画标识");
  assert.equal(room.extraRollAvailable, true, "掷出 12 点后应保留一次额外投骰机会");
  assert.equal(room.pendingLanding?.kind, "buy", "前进后应先完成落地操作");
  const cardAfterRolling = applyMonopolyRoomAction(room, { action: "card", playerId: "a", card: "fixed_dice", target: { dice: 6 } });
  assert.equal(cardAfterRolling, room, "投骰后不得再使用道具卡");
  room = applyMonopolyRoomAction(room, { action: "buy", playerId: "a", propertyIndex: 12 });
  assert.equal(room.pendingLanding, undefined, "完成落地操作后不应遗留待处理状态");
  assert.equal(room.game.properties[12].ownerDeviceId, "a", "购买应完成当前地块的唯一操作");
  assert.equal(room.game.currentPlayerId, "a", "12 点奖励应仍由当前玩家继续操作");
  assert.equal(room.turnRolled, false, "买地后应直接回到 12 点奖励的投骰前状态，不能继续升级同一地块");
  room.game.players[0].cards = ["fixed_dice"];
  room = applyMonopolyRoomAction(room, { action: "card", playerId: "a", card: "fixed_dice", target: { dice: 6 } });
  assert.equal(room.game.players[0].forcedDice, 6, "额外投骰前允许使用道具卡");
  room = applyMonopolyRoomAction(room, { action: "roll", playerId: "a" }, () => 0);
  assert.equal(room.lastDice?.total, 6, "指定骰应记录实际投骰点数");
  assert.equal(room.game.players[0].position, 18, "指定 6 点后应继续前进");
  room = applyMonopolyRoomAction(room, { action: "skip_landing", playerId: "a" });
  assert.equal(room.game.currentPlayerId, "b", "没有后续操作时应自动切换到下一位玩家");
  assert.equal(room.turnRolled, false, "新玩家应进入投骰前状态");
  room.game.currentPlayerId = "a";
  room.game.players[0].position = 6;
  room.game.players[0].cards = ["fixed_dice"];
  room.extraRollAvailable = false;
  const coinsBeforeAutoUpgrade = room.game.players[0].coins;
  room = applyMonopolyRoomAction(room, { action: "card", playerId: "a", card: "fixed_dice", target: { dice: 6 } });
  room = applyMonopolyRoomAction(room, { action: "roll", playerId: "a" }, () => 0);
  assert.equal(room.game.properties[12].level, "level2", "再次踩到自己的小屋应自动升级");
  assert.equal(room.game.players[0].coins, coinsBeforeAutoUpgrade, "自动升级不应扣除金币");
  assert.equal(room.game.currentPlayerId, "b", "自动升级后应直接切换到下一位玩家");
  let announcementRoom = createMonopolyRoomState({ roomId: "monopoly-announcement", host, startingCoins: 5000, maxRounds: 20, now: 1 });
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "join", player: { deviceId: "b", nickname: "乙", online: true, ready: false } });
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "ready", playerId: "a", ready: true });
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "ready", playerId: "b", ready: true });
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "start", playerId: "a" });
  announcementRoom.game.players[0].position = 39;
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "roll", playerId: "a" }, () => .4);
  assert.equal(announcementRoom.lastAnnouncement?.kind, "event", "随机事件应同步为全房间可见的横幅公告");
  announcementRoom.game.currentPlayerId = "a";
  announcementRoom.game.players[0].cards = ["frame"];
  announcementRoom.game.turnStartedAt = 1;
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "card", playerId: "a", card: "frame", target: { playerId: "b" } });
  assert.equal(announcementRoom.lastAnnouncement?.kind, "card", "道具卡成功使用后应同步为全房间可见的横幅公告");
  assert.ok(announcementRoom.game.turnStartedAt > 1, "玩家成功使用道具后应重新开始 60 秒操作倒计时");
  announcementRoom.game.currentPlayerId = "a";
  announcementRoom.game.players[0].position = 0;
  announcementRoom.game.turnStartedAt = 1;
  announcementRoom = applyMonopolyRoomAction(announcementRoom, { action: "roll", playerId: "a" }, () => 0);
  assert.ok(announcementRoom.game.turnStartedAt > 1, "玩家投骰后应重新开始 60 秒操作倒计时");
  let jailRoom = createMonopolyRoomState({ roomId: "monopoly-jail", host, startingCoins: 5000, maxRounds: 20, now: 1 });
  jailRoom = applyMonopolyRoomAction(jailRoom, { action: "join", player: { deviceId: "b", nickname: "乙", online: true, ready: false } });
  jailRoom = applyMonopolyRoomAction(jailRoom, { action: "ready", playerId: "a", ready: true });
  jailRoom = applyMonopolyRoomAction(jailRoom, { action: "ready", playerId: "b", ready: true });
  jailRoom = applyMonopolyRoomAction(jailRoom, { action: "start", playerId: "a" });
  jailRoom.game.players[0].jailTurns = 2;
  jailRoom.game.turnStartedAt = 1;
  jailRoom = applyMonopolyRoomAction(jailRoom, { action: "roll", playerId: "a" }, () => 0);
  assert.ok(jailRoom.game.turnStartedAt > 1, "监狱中的玩家完成本回合操作后也应重新开始 60 秒操作倒计时");
  console.log("monopoly room rules ok");
} finally {
  await rm(tempDir, { recursive: true, force: true });
}
