  rentRoom.game.players[0].position = 39;
  rentRoom.game.properties[1] = { ...rentRoom.game.properties[1], ownerDeviceId: "b", level: "house", buildingVariant: 0 };
  rentRoom = applyMonopolyRoomAction(rentRoom, { action: "roll", playerId: "a" }, () => 0);
  assert.equal(rentRoom.lastAnnouncement?.kind, "rent", "踩中敌方地产并支付过路费应广播收费横幅");
